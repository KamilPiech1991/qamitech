      <li><strong>Spójny NAP</strong> — nazwa, adres i telefon (Name, Address, Phone) muszą być identyczne we wszystkich miejscach w sieci.</li>
      <li><strong>Ustrukturyzowane dane</strong> — schema markup pomaga AI "przeczytać" stronę i wyciągnąć kluczowe informacje o firmie.</li>
